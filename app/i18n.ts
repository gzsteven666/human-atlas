function replaceTerms(name: string): string {
  const normalized = name.toLowerCase().replace(/[–—-]/g, ' ').replace(/\s+/g, ' ').trim();
  // English anatomical labels commonly use “X of Y”; Chinese medical names read “Y 的 X”.
  const ofIndex = normalized.indexOf(' of ');
  if (ofIndex > 0) return `${replaceTerms(normalized.slice(ofIndex + 4))}的${replaceTerms(normalized.slice(0, ofIndex))}`;
  let result = normalized;
  const terms = Object.keys(TERMS).sort((a, b) => b.length - a.length);
  for (const term of terms) {
    result = result.replace(new RegExp(`\\b${term}\\b`, 'g'), TERMS[term]);
  }
  result = result.replace(/\bthe\b/g, '').replace(/\s+/g, ' ').trim();
  result = result.replace(/\s*的\s*/g, '的');
  // Anatomical Chinese reads naturally with positional adjectives before the noun.
  result = result.replace(/(右|左|前|后|上|下|内侧|外侧|近端|远端|浅|深)(?=[^的]*?(动脉|静脉|神经|肌|骨|软骨|韧带|腺|管|叶|支|干|血管))/g, '$1');
  return result.replace(/(?<=[\u3400-\u9fff\d])\s+(?=[\u3400-\u9fff\d])/g, '').replace(/\biii\b/gi, 'Ⅲ').replace(/\bii\b/gi, 'Ⅱ').replace(/\bvi\b/gi, 'Ⅵ').replace(/\bvii\b/gi, 'Ⅶ').replace(/\bviii\b/gi, 'Ⅷ').replace(/\biv\b/gi, 'Ⅳ').replace(/\bv\b/gi, 'Ⅴ').replace(/\bix\b/gi, 'Ⅸ').replace(/总颈/g, '颈总');
}

export function anatomyName(name: string, locale: Locale): string {
  if (locale === 'en') return name;
  const key = name.toLowerCase().trim();
  return EXACT_ZH[key] ?? replaceTerms(name);
}

